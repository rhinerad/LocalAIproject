#!/usr/bin/env python3
"""DSPy evaluation suite for temporal-physics prompt injection.

Grades orchestrator traces under logs/run_traces/ plus a small gold set
(open hallway vs static security camera). The judge LM is SpaceXAI grok-4.6
(XAI_API_KEY, https://api.x.ai/v1) — OpenAI-compatible, not GPT-4o/Claude.

Requires: pip install dspy  and  XAI_API_KEY.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

try:
    import dspy
except ImportError:  # pragma: no cover
    dspy = None

ROOT = Path(__file__).resolve().parent
TRACE_DIR = ROOT / "logs" / "run_traces"
EVAL_DIR = ROOT / "logs" / "dspy_eval"
XAI_BASE_URL = "https://api.x.ai/v1"
DEFAULT_JUDGE_MODEL = "grok-4.6"

REQUIRED_PHYSICS = (
    "first-person camcorder tracking",
    "heavy VHS artifacting",
    "handheld walking momentum",
    "continuous unbroken shot",
    "realistic camera shake",
    "1990s home video aesthetic",
)
HANDHELD_FAMILY = (
    "first-person camcorder tracking",
    "handheld walking momentum",
    "realistic camera shake",
)


if dspy is not None:
    class ValidateTemporalPhysics(dspy.Signature):
        """Evaluate whether the video prompt injection correctly applies cinematographic physics without conflicting with user instructions."""
        base_prompt: str = dspy.InputField(desc="The original user request.")
        injected_prompt: str = dspy.InputField(desc="The final prompt generated by the Orchestrator.")
        rationale: str = dspy.OutputField(desc="Step-by-step reasoning evaluating the formatting, conflicts, and required aesthetics.")
        score: bool = dspy.OutputField(desc="True if the injected prompt is flawless and maintains formatting/conflict rules, False otherwise.")
else:  # pragma: no cover
    ValidateTemporalPhysics = None


def extract_injected_prompt(graph: dict) -> str:
    """Pull the orchestrator's positive CLIP text from a saved Comfy graph."""
    if not isinstance(graph, dict):
        return ""
    nodes = graph.get("prompt") if isinstance(graph.get("prompt"), dict) else graph
    if not isinstance(nodes, dict):
        return ""
    positive = nodes.get("2")
    if isinstance(positive, dict):
        text = (positive.get("inputs") or {}).get("text")
        if text:
            return str(text)
    chunks = []
    for node in nodes.values():
        if not isinstance(node, dict) or node.get("class_type") != "CLIPTextEncode":
            continue
        title = str((node.get("_meta") or {}).get("title") or "")
        text = str((node.get("inputs") or {}).get("text") or "")
        if "FaceDetailer" in title:
            continue
        if "Positive" in title or not chunks:
            chunks.append(text)
    return chunks[0] if chunks else ""


def load_trace_examples(trace_dir: Path = TRACE_DIR) -> list[dict]:
    """Load DSPy-eval rows from live orchestrator JSON traces."""
    rows = []
    if not trace_dir.is_dir():
        return rows
    for path in sorted(trace_dir.glob("*.json")):
        if path.name.endswith("_result.json") or path.name.endswith("_summary.json"):
            continue
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        request = payload.get("request") if isinstance(payload.get("request"), dict) else {}
        style = str(request.get("style") or "").lower()
        model_type = str(request.get("model_type") or "").lower()
        if style != "backrooms" and model_type not in {"video", "wan", "minimax", "i2v", "t2v"}:
            continue
        base = str(request.get("base_prompt") or "")
        injected = extract_injected_prompt(payload)
        if not base or not injected:
            continue
        rows.append({
            "case_id": str(payload.get("case_id") or path.stem),
            "source": str(path),
            "base_prompt": base,
            "injected_prompt": injected,
        })
    return rows


def gold_examples() -> list[dict]:
    """Deterministic hallway vs locked-camera pairs for the judge."""
    sys.path.insert(0, str(ROOT / "local_agent"))
    from temporal_physics import inject_temporal_physics

    open_base = "A yellow hallway with flickering fluorescent lights"
    locked_base = "A yellow hallway, static security camera footage"
    return [
        {
            "case_id": "gold_open_hallway",
            "source": "gold",
            "base_prompt": open_base,
            "injected_prompt": inject_temporal_physics(open_base, style="backrooms"),
        },
        {
            "case_id": "gold_static_security",
            "source": "gold",
            "base_prompt": locked_base,
            "injected_prompt": inject_temporal_physics(locked_base, style="backrooms"),
        },
        {
            "case_id": "gold_tripod",
            "source": "gold",
            "base_prompt": "A static tripod shot of a yellow hallway",
            "injected_prompt": inject_temporal_physics(
                "A static tripod shot of a yellow hallway", style="backrooms",
            ),
        },
        {
            "case_id": "gold_dolly",
            "source": "gold",
            "base_prompt": "A yellow hallway, dolly in toward the far door",
            "injected_prompt": inject_temporal_physics(
                "A yellow hallway, dolly in toward the far door", style="backrooms",
            ),
        },
    ]


def coerce_bool(value) -> bool:
    if isinstance(value, bool):
        return value
    text = str(value or "").strip().lower()
    return text in {"true", "1", "yes", "pass", "flawless"}


def evaluate_temporal_physics(example, pred, trace=None, **_kwargs) -> bool:
    """Compiler metric: ``injected_prompt`` obeys Backrooms physics and conflicts.

    Used by BootstrapFewShot on ``TemporalPhysicsInjector``. Does not require
    a judge ``score`` field.
    """
    injected = str(
        getattr(pred, "injected_prompt", None)
        or getattr(example, "injected_prompt", "")
        or ""
    )
    base = str(getattr(example, "base_prompt", "") or "")
    injected_l = injected.lower()
    base_l = base.lower()
    locked = any(term in base_l for term in (
        "static security", "static shot", "static camera", "tripod", "cctv",
    ))
    specified = any(term in base_l for term in (
        "dolly", "pan left", "pan right", "tilt up", "tilt down",
    ))
    if locked or specified:
        if any(term.lower() in injected_l for term in HANDHELD_FAMILY):
            return False
        if "vhs" not in injected_l and "1990s" not in injected_l:
            return False
        return True
    return all(term.lower() in injected_l for term in REQUIRED_PHYSICS)


def temporal_physics_metric(example, pred, trace=None, **_kwargs) -> bool:
    """Judge metric: physics rules plus ValidateTemporalPhysics.score."""
    if not evaluate_temporal_physics(example, pred, trace=trace):
        return False
    if not hasattr(pred, "score"):
        return True
    return coerce_bool(getattr(pred, "score", False))


def configure_lm(model: str = DEFAULT_JUDGE_MODEL):
    if dspy is None:
        raise RuntimeError("dspy is not installed. Run: pip install dspy")
    api_key = os.environ.get("XAI_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError("XAI_API_KEY is not set.")
    lm = dspy.LM(
        f"openai/{model}",
        api_key=api_key,
        api_base=XAI_BASE_URL,
        temperature=0.0,
        max_tokens=2048,
    )
    dspy.configure(lm=lm)
    return lm


def build_judge():
    if dspy is None or ValidateTemporalPhysics is None:
        raise RuntimeError("dspy is not installed. Run: pip install dspy")
    return dspy.ChainOfThought(ValidateTemporalPhysics)


def to_dspy_examples(rows: list[dict]):
    if dspy is None:
        raise RuntimeError("dspy is not installed. Run: pip install dspy")
    return [
        dspy.Example(
            base_prompt=row["base_prompt"],
            injected_prompt=row["injected_prompt"],
        ).with_inputs("base_prompt", "injected_prompt")
        for row in rows
    ]


def evaluate_rows(rows: list[dict], *, model: str = DEFAULT_JUDGE_MODEL) -> dict:
    configure_lm(model)
    judge = build_judge()
    results = []
    passed = 0
    for row in rows:
        pred = judge(base_prompt=row["base_prompt"], injected_prompt=row["injected_prompt"])
        example = type("Ex", (), row)()
        ok = temporal_physics_metric(example, pred)
        passed += int(ok)
        results.append({
            "case_id": row.get("case_id"),
            "source": row.get("source"),
            "base_prompt": row["base_prompt"],
            "injected_prompt": row["injected_prompt"],
            "rationale": str(getattr(pred, "rationale", "")),
            "score": coerce_bool(getattr(pred, "score", False)),
            "metric_pass": ok,
        })
    return {
        "model": model,
        "n": len(rows),
        "passed": passed,
        "failed": len(rows) - passed,
        "results": results,
    }


def main(argv=None) -> int:
    del argv
    rows = gold_examples() + load_trace_examples()
    if not rows:
        print("No gold rows or traces to evaluate.", file=sys.stderr)
        return 2
    print(f"Evaluating {len(rows)} temporal-physics prompts with {DEFAULT_JUDGE_MODEL}...")
    report = evaluate_rows(rows)
    EVAL_DIR.mkdir(parents=True, exist_ok=True)
    out = EVAL_DIR / "temporal_physics_eval.json"
    out.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(json.dumps({k: report[k] for k in ("model", "n", "passed", "failed")}, indent=2))
    print(f"wrote {out}")
    return 0 if report["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
