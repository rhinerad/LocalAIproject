#!/usr/bin/env python3
"""Conversation storage — the part that makes it feel like a desktop app.

Chats persist across restarts, exactly as they would in ChatGPT desktop. One JSON
file per conversation under `local_agent/chats/`, so a conversation is greppable,
diffable, and trivially backed up. No database, nothing to install.

Titles are derived from the first message rather than generated by the model:
asking a 14B CPU model to name a chat costs several seconds before the operator
sees anything, and it is not worth it.
"""
from __future__ import annotations

import json
import re
import threading
import time
import uuid
from contextlib import contextmanager
from pathlib import Path

from atomic_io import atomic_write_text
from production_integrity import process_lock

DIR = Path(__file__).resolve().parent / "chats"
_GUARD = threading.Lock()
_CONVERSATION_GUARDS: dict[str, threading.Lock] = {}
_HELD = threading.local()


def _thread_guard(cid: str) -> threading.Lock:
    with _GUARD:
        lock = _CONVERSATION_GUARDS.get(cid)
        if lock is None:
            lock = threading.Lock()
            _CONVERSATION_GUARDS[cid] = lock
        return lock


@contextmanager
def conversation_lock(cid: str):
    """Serialize one conversation across threads and across processes.

    Desktop and phone writers share the JSON file. The thread lock keeps a
    second thread in this process off the OS lock; the OS lock covers the
    other process. Re-entering from the same thread is allowed so a mutator
    can call save() while it already holds the lock.
    """
    held = getattr(_HELD, "cids", None)
    if held is None:
        held = set()
        _HELD.cids = held
    if cid in held:
        yield
        return
    guard = _thread_guard(cid)
    with guard:
        with process_lock(DIR / f"{cid}.lock", timeout=30):
            held.add(cid)
            try:
                yield
            finally:
                held.discard(cid)


def _path(cid: str) -> Path:
    if not re.fullmatch(r"[A-Za-z0-9_-]{4,40}", cid):
        raise ValueError(f"bad conversation id {cid!r}")
    return DIR / f"{cid}.json"


def title_from(text: str, limit: int = 48) -> str:
    t = " ".join((text or "").split())
    if not t:
        return "New chat"
    return t[:limit] + ("…" if len(t) > limit else "")


WORKSPACES = {"auto", "general", "equal_shares"}


def normalize_workspace(value: str | None) -> str:
    workspace = str(value or "auto").strip().lower()
    if workspace not in WORKSPACES:
        raise ValueError(f"unknown workspace {workspace!r}")
    return workspace


def create(first_message: str = "", model: str = "", workspace: str = "auto",
           routing: str = "") -> dict:
    DIR.mkdir(parents=True, exist_ok=True)
    routing = str(routing or "").strip()
    if routing and routing != "auto_farm":
        raise ValueError(f"unknown routing {routing!r}")
    conv = {
        "id": uuid.uuid4().hex[:16],
        "title": title_from(first_message),
        "created": time.time(),
        "updated": time.time(),
        "model": "" if model is None else str(model),
        "routing": routing,
        "workspace": normalize_workspace(workspace),
        "messages": [],
    }
    save(conv)
    return conv


def save(conv: dict) -> dict:
    with conversation_lock(conv["id"]):
        conv["updated"] = time.time()
        p = _path(conv["id"])
        atomic_write_text(p, json.dumps(conv, indent=2, ensure_ascii=False))
        return conv


def mutate(cid: str, fn):
    """Load, modify, and save one conversation under its lock.

    fn(conv) returns False when the loaded document should stay as it was.
    """
    if not cid:
        return None
    try:
        _path(cid)
    except ValueError:
        return None
    with conversation_lock(cid):
        conv = load(cid)
        if conv is None:
            return None
        if fn(conv) is False:
            return conv
        return save(conv)


def load(cid: str) -> dict | None:
    """Return the conversation, or None.

    A missing, empty or malformed id returns None rather than raising. The GUI
    sends `id: null` for the very first message of a new chat, and an exception
    there crashed the request before a reply could start — the first thing a new
    user would ever do. `_path` still refuses a bad id, so nothing escapes the
    chats directory; this only decides how the caller hears about it.
    """
    if not cid:
        return None
    try:
        p = _path(cid)
    except ValueError:
        return None
    if not p.is_file():
        return None
    try:
        conv = json.loads(p.read_text(encoding="utf8"))
        # Backward-compatible source migration. Existing desktop chats predate
        # the transport field; callers see the normalized shape immediately and
        # the value persists on the next normal save.
        for message in conv.get("messages", []):
            message.setdefault("source", "desktop")
        conv.setdefault("workspace", "auto")
        return conv
    except Exception:
        return None


def listing() -> list[dict]:
    if not DIR.is_dir():
        return []
    out = []
    for p in DIR.glob("*.json"):
        try:
            d = json.loads(p.read_text(encoding="utf8"))
            out.append({"id": d["id"], "title": d.get("title") or "New chat",
                        "updated": d.get("updated", 0),
                        "messages": len(d.get("messages", [])),
                        "model": d.get("model", ""),
                        "routing": d.get("routing", ""),
                        "workspace": d.get("workspace", "auto"),
                        "last_tier": d.get("last_tier", "")})
        except Exception:
            continue
    return sorted(out, key=lambda x: -x["updated"])


def set_last_tier(cid: str, tier: str) -> None:
    """Record which model tier handled the most recent turn."""
    def _apply(conv: dict):
        conv["last_tier"] = tier
    mutate(cid, _apply)


def set_model(cid: str, model: str) -> bool:
    """Pin a model once. Existing chats may not silently switch models."""
    outcome = {"ok": False}

    def _apply(conv: dict):
        current = str(conv.get("model") or "")
        if current and current != model:
            return False
        conv["model"] = model
        outcome["ok"] = True

    if mutate(cid, _apply) is None:
        return False
    return outcome["ok"]


def set_workspace(cid: str, workspace: str) -> bool:
    """Pin workspace separately from model; never switch an active chat."""
    selected = normalize_workspace(workspace)
    outcome = {"ok": False}

    def _apply(conv: dict):
        current = normalize_workspace(conv.get("workspace"))
        if current != "auto" and current != selected:
            return False
        conv["workspace"] = selected
        outcome["ok"] = True

    if mutate(cid, _apply) is None:
        return False
    return outcome["ok"]


def rename(cid: str, title: str) -> bool:
    def _apply(conv: dict):
        conv["title"] = title_from(title)
    return mutate(cid, _apply) is not None


def delete(cid: str) -> bool:
    """Move to `chats/_deleted/`, never unlink.

    This project's standing rule is that nothing is destroyed, and a chat can
    contain the only written record of a decision. Recoverable beats tidy.
    """
    try:
        _path(cid)
    except ValueError:
        return False
    with conversation_lock(cid):
        p = _path(cid)
        if not p.is_file():
            return False
        trash = DIR / "_deleted"
        trash.mkdir(parents=True, exist_ok=True)
        p.replace(trash / f"{cid}.{int(time.time())}.json")
        return True


def append(cid: str, role: str, content: str, meta: dict | None = None,
           source: str = "desktop") -> dict | None:
    if source not in {"desktop", "phone"}:
        raise ValueError(f"unknown conversation source {source!r}")

    def _apply(conv: dict):
        entry = {"role": role, "content": content, "at": time.time(), **(meta or {})}
        entry["source"] = source  # meta cannot spoof the transport provenance
        conv["messages"].append(entry)
        if len(conv["messages"]) == 1 and role == "user":
            conv["title"] = title_from(content)

    return mutate(cid, _apply)


def truncate_after(cid: str, index: int) -> dict | None:
    """Drop everything after `index`. Backs a Regenerate / Edit button."""
    def _apply(conv: dict):
        conv["messages"] = conv["messages"][:index + 1]
    return mutate(cid, _apply)
