#!/usr/bin/env python3
"""Clear the Stage-1 audio state produced under the corrupted prompts.

WHY
---
The 2026-08-17 pass rendered every clip with a prepended `AUDIO-FIRST REFERENCE
JOBS` header, and 46 of them additionally fell back to the pre-native prompt.
Nothing from that pass is usable. The manifest still carries its verdicts, and
the renderer treats `needs_ear_review` and `auto_pass_pending_continuity_review`
as finished — so those clips would be skipped forever and the corrupt takes would
survive into the film.

Operator instruction, 2026-08-18: "just erase the 83 pending clips since they
were all done incorrectly."

WHAT "ERASE" MEANS HERE
-----------------------
**State is cleared. Media is not deleted.** CLAUDE.md: "Never delete a raw
generation, an approved reference, a manifest, an audit record, or source audio.
Versioned siblings only." The operator named a set of clips, not a set of files,
so this tool takes the non-destructive route that satisfies the intent:

  1. The whole manifest is copied to a timestamped sibling first.
  2. Matching clip records are removed from the live manifest, so those clips
     re-render from scratch on the next pass.
  3. Their rendered media is MOVED into a clearly labelled quarantine folder,
     out of the working tree but still on disk.

Nothing is unrecoverable. If a clip turns out to have been fine, its raws and its
manifest record are both still there.

WHAT IT DOES NOT TOUCH
----------------------
Clips marked `accepted`. There are none today, but if the operator has accepted
something by ear since, this will not throw it away. Use `--include-accepted`
deliberately if that is really wanted.
"""
from __future__ import annotations

import argparse
import json
import shutil
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EQ = ROOT / "outputs" / "equal_shares"
MANIFEST = EQ / "audio_pass_manifest.json"
# The audio pass does NOT write to ComfyUI-Shared. Its backend runs with its own
# output root inside the project, confirmed from the manifest's own
# `source_video` paths:
#   outputs/equal_shares/runtime/codex_comfy_runtime/output/story/AUDIO_<clip>/
# Candidate WAVs and validation reports live beside it.
SHARED_OUT = EQ / "runtime" / "codex_comfy_runtime" / "output" / "story"
CANDIDATES = EQ / "audio" / "audio_pass_candidates"
VALIDATION = EQ / "audio_validation"
QUARANTINE = EQ / "_QUARANTINE_corrupt_prompt_pass_2026-08-17"

# Everything from the corrupt pass. `accepted` is deliberately excluded.
CORRUPT_STATUSES = {
    "needs_ear_review",
    "auto_pass_pending_continuity_review",
    "retry_required",
    "render_failed",
    "render_error",
    "pending_ear_review",
    "human_review_needed",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true",
                    help="without this, only reports what would change")
    ap.add_argument("--include-accepted", action="store_true",
                    help="also clear clips the operator has accepted (rarely right)")
    ap.add_argument("--shared-output", default=str(SHARED_OUT))
    ap.add_argument("--quarantine", default=str(QUARANTINE))
    args = ap.parse_args()

    if not MANIFEST.is_file():
        print(f"no manifest at {MANIFEST} — nothing to reset")
        return 0

    data = json.loads(MANIFEST.read_text(encoding="utf-8-sig"))
    clips = data.get("clips", {})
    statuses = set(CORRUPT_STATUSES)
    if args.include_accepted:
        statuses.add("accepted")

    targets = {cid: rec for cid, rec in clips.items()
               if rec.get("status") in statuses}
    kept = {cid: rec for cid, rec in clips.items() if cid not in targets}

    from collections import Counter
    print(f"manifest holds {len(clips)} clip records")
    print(f"  clearing : {len(targets)}  {dict(Counter(r.get('status') for r in targets.values()))}")
    print(f"  keeping  : {len(kept)}     {dict(Counter(r.get('status') for r in kept.values()))}")

    attempts = sum(len(r.get("attempts", [])) for r in targets.values())
    print(f"  attempt records inside those: {attempts}")

    src_root, qroot = Path(args.shared_output), Path(args.quarantine)
    movable = [(cid, src_root / f"AUDIO_{cid}") for cid in targets
               if (src_root / f"AUDIO_{cid}").is_dir()]
    # Derived artefacts named after the cleared clips: the extracted candidate
    # WAVs and their validation reports. Both are regenerated by a fresh render,
    # and leaving them behind would let a later tool pick up a corrupt-pass WAV
    # as if it were current.
    loose = []
    for cid in targets:
        loose += [p for p in CANDIDATES.glob(f"{cid}_a*_full.wav")]
        loose += [p for p in VALIDATION.glob(f"{cid}_a*.json")]
    print(f"  rendered media folders to quarantine: {len(movable)}")
    print(f"  candidate WAVs + validation reports : {len(loose)}")
    if not movable:
        print(f"    (no AUDIO_* folders under {src_root})")

    if not args.apply:
        print("\n--apply not given; nothing written")
        return 0

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup = MANIFEST.with_name(f"audio_pass_manifest.BEFORE_RESET_{stamp}.json")
    shutil.copy2(MANIFEST, backup)
    print(f"\nmanifest backed up -> {backup.name}")

    qroot.mkdir(parents=True, exist_ok=True)
    moved = 0
    for cid, folder in movable:
        dest = qroot / folder.name
        if dest.exists():
            dest = qroot / f"{folder.name}_{stamp}"
        shutil.move(str(folder), str(dest))
        moved += 1
    if moved:
        print(f"quarantined {moved} media folders -> {qroot}")

    moved_loose = 0
    for p in loose:
        sub = qroot / p.parent.name
        sub.mkdir(parents=True, exist_ok=True)
        dest = sub / p.name
        if dest.exists():
            dest = sub / f"{p.stem}_{stamp}{p.suffix}"
        shutil.move(str(p), str(dest))
        moved_loose += 1
    if moved_loose:
        print(f"quarantined {moved_loose} candidate WAVs / validation reports")

    (qroot / "README.md").write_text(
        "# Quarantined — Stage-1 takes from the corrupt-prompt pass\n\n"
        "Every take in here was rendered on or before 2026-08-17 with a prepended\n"
        "`AUDIO-FIRST REFERENCE JOBS` header on the prompt, and 46 clips also fell\n"
        "back to the pre-native prompt set. Confirmed by extracting the workflow\n"
        "embedded in the output PNGs — see `docs/GOLDEN_REFERENCE/README.md`.\n\n"
        "They are kept, not deleted, as evidence of the fault and in case any\n"
        "single take turns out to be usable. Nothing in here is current. Do not\n"
        "feed any of it into the film, and do not cut a voice master from it.\n\n"
        f"Moved {moved} clip folders on {datetime.now().isoformat(timespec='seconds')}\n"
        f"by `work/reset_corrupt_audio_pass.py`.\n",
        encoding="utf8")

    data["clips"] = kept
    data["reset_history"] = data.get("reset_history", []) + [{
        "at": datetime.now().isoformat(timespec="seconds"),
        "cleared": sorted(targets),
        "reason": ("rendered under the corrupted prompts of 2026-08-17 — prepended "
                   "header on all clips, 46 also on the pre-native prompt set"),
        "manifest_backup": backup.name,
        "media_quarantine": str(qroot),
    }]
    MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"manifest now holds {len(kept)} clip records; "
          f"{len(targets)} clips will render from scratch")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
